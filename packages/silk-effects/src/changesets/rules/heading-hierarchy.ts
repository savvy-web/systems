/**
 * Lint rule: changeset-heading-hierarchy (CSH001).
 *
 * @remarks
 * Kit twin of `HeadingHierarchyRule`. Forbids h1 headings and sequential
 * depth skips.
 *
 * @internal
 */

import { MarkdownVisitor } from "@effected/markdown";
import { RULE_DOCS } from "../constants.js";
import type { LintRule, RuleFinding } from "./types.js";
import { finding } from "./types.js";

const RULE = "changeset-heading-hierarchy";

/**
 * Validate heading depth structure.
 *
 * @internal
 */
export const headingHierarchy: LintRule = (root) => {
	const findings: RuleFinding[] = [];
	let prevDepth = 0;

	for (const event of MarkdownVisitor.walk(root)) {
		if (event._tag !== "Enter" || event.node.type !== "heading") continue;
		const node = event.node;

		if (node.depth === 1) {
			findings.push(
				finding(
					RULE,
					`h1 headings are not allowed in changeset files. Use h2 (##) for top-level sections like "## Features" or "## Bug Fixes". h1 is reserved for the version title generated by the changelog formatter. See: ${RULE_DOCS.CSH001}`,
					node,
				),
			);
			continue;
		}

		if (prevDepth > 0 && node.depth > prevDepth + 1) {
			findings.push(
				finding(
					RULE,
					`Heading level skipped: expected h${prevDepth + 1} or lower, found h${node.depth}. Headings must increase sequentially (h2 → h3 → h4). Add the missing intermediate level or reduce this heading's depth. See: ${RULE_DOCS.CSH001}`,
					node,
				),
			);
		}

		prevDepth = node.depth;
	}

	return findings;
};
